// Generates migrations/0008_seed_test2.sql from scripts/test2-content.mjs.
// Run: node scripts/generate-test2-seed.mjs
// ID allocation (explicit, see DATABASE_README.md):
//   tests: 2 | test_parts: 3 (Part A), 4 (Part B)
//   dimensions: 13 (A/B2), 14 (A/C1C2), 15 (B/B2), 16 (B/C1C2)
//   shared_resources: 1-20 audio (Q1-20), 21-26 passages
//   question_groups & questions: 100 + question number (101-145)

import { writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TEST2, LISTENING, PASSAGES, READING, CONVERSION_BANDS } from './test2-content.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SEED_TS = 1751860800000;

const q = (s) => (s == null ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`);
const pad2 = (n) => String(n).padStart(2, '0');
const pad3 = (n) => String(n).padStart(3, '0');

// --- Invariant checks ---
if (LISTENING.length !== 20) throw new Error(`Expected 20 listening questions, got ${LISTENING.length}`);
if (READING.length !== 25) throw new Error(`Expected 25 reading questions, got ${READING.length}`);
if (PASSAGES.length !== 6) throw new Error(`Expected 6 passages, got ${PASSAGES.length}`);
const readingNumbers = READING.map((r) => r.n);
if (readingNumbers.join(',') !== Array.from({ length: 25 }, (_, i) => i + 21).join(',')) {
  throw new Error('Reading questions must be numbered 21-45 continuously');
}
for (const item of [...LISTENING, ...READING]) {
  if (item.options.length !== 4) throw new Error(`Q${item.n} does not have 4 options`);
  if (!['A', 'B', 'C', 'D'].includes(item.correct)) throw new Error(`Q${item.n} bad correct answer`);
}

const DIM_IDS = {
  'A|B2': 13,
  'A|C1/C2': 14,
  'B|B2': 15,
  'B|C1/C2': 16,
};

const lines = [];
lines.push('-- Seed: Test 2 (Paper II — Listening & Reading) into the unified test bank.');
lines.push('-- GENERATED by scripts/generate-test2-seed.mjs from scripts/test2-content.mjs — do not hand-edit.');
lines.push('-- 20 listening groups (audio resources 1-20) + 25 reading groups (passages 21-26),');
lines.push('-- CEFR difficulty dimensions (B2 / C1-C2) per part, per-part conversion grids.');
lines.push('');

// tests (id 2) — draft until the Test 2 UI stage ships
lines.push(
  `INSERT INTO tests (id, test_code, name, description, time_limit_seconds, status, created_at) VALUES (2, '02', ${q(TEST2.name)}, ${q(TEST2.description)}, ${TEST2.timeLimitSeconds}, 'draft', ${SEED_TS});`,
);
lines.push('');

// test_parts (ids 3, 4)
lines.push(`INSERT INTO test_parts (id, test_id, part_code, name, skill, sort_order) VALUES (3, 2, '01', ${q('Part A — Listening')}, 'listening', 1);`);
lines.push(`INSERT INTO test_parts (id, test_id, part_code, name, skill, sort_order) VALUES (4, 2, '02', ${q('Part B — Reading')}, 'reading', 2);`);
lines.push('');

// dimensions: CEFR difficulty bands per part
lines.push(`INSERT INTO dimensions (id, test_part_id, dimension_code, key, name, short, sort_order) VALUES (13, 3, '01', 'listeningB2', ${q('Listening — B2 Items')}, 'B2', 1);`);
lines.push(`INSERT INTO dimensions (id, test_part_id, dimension_code, key, name, short, sort_order) VALUES (14, 3, '02', 'listeningC1C2', ${q('Listening — C1/C2 Items')}, 'C1/C2', 2);`);
lines.push(`INSERT INTO dimensions (id, test_part_id, dimension_code, key, name, short, sort_order) VALUES (15, 4, '01', 'readingB2', ${q('Reading — B2 Items')}, 'B2', 1);`);
lines.push(`INSERT INTO dimensions (id, test_part_id, dimension_code, key, name, short, sort_order) VALUES (16, 4, '02', 'readingC1C2', ${q('Reading — C1/C2 Items')}, 'C1/C2', 2);`);
lines.push('');

// shared_resources 1-20: audio with transcript
for (const item of LISTENING) {
  const file = `20260701_${pad2(item.n)}.mp3`;
  const meta = JSON.stringify({ file, genre: item.genre, skill: item.skill, audioKind: item.audioKind });
  lines.push(
    `INSERT INTO shared_resources (id, test_id, resource_type, title, content_url, text_content, metadata, created_at) ` +
      `VALUES (${item.n}, 2, 'audio', ${q(`Listening Q${item.n} — ${item.genre}`)}, ${q(`/api/assets/audio/test-02/${file}`)}, ${q(item.transcript)}, ${q(meta)}, ${SEED_TS});`,
  );
}
lines.push('');

// shared_resources 21-26: reading passages
for (const p of PASSAGES) {
  const resourceId = 20 + p.index;
  const skills = Object.fromEntries(READING.filter((r) => r.passage === p.index).map((r) => [`Q${r.n}`, r.skill]));
  const meta = JSON.stringify({ genre: p.genre, attribution: p.attribution ?? undefined, skills });
  lines.push(
    `INSERT INTO shared_resources (id, test_id, resource_type, title, content_url, text_content, metadata, created_at) ` +
      `VALUES (${resourceId}, 2, 'text', ${q(p.title)}, NULL, ${q(p.text)}, ${q(meta)}, ${SEED_TS});`,
  );
}
lines.push('');

// question_groups + questions
const emit = (item, part, resourceId) => {
  const groupId = 100 + item.n;
  const partId = part === 'A' ? 3 : 4;
  const partCode = part === 'A' ? '01' : '02';
  const dimId = DIM_IDS[`${part}|${item.level}`];
  if (!dimId) throw new Error(`No dimension for ${part}/${item.level}`);
  const ss = item.level === 'B2' ? '01' : '02';
  const ggg = pad3(item.n);
  const code = `02-${partCode}-${ss}-${ggg}-01`;
  const [a, b, c, d] = item.options;

  lines.push(
    `INSERT INTO question_groups (id, test_id, test_part_id, dimension_id, shared_resource_id, group_code, canonical_number, legacy_qid, variant_count, sort_order) ` +
      `VALUES (${groupId}, 2, ${partId}, ${dimId}, ${resourceId}, '${ggg}', ${item.n}, NULL, 1, ${item.n});`,
  );
  lines.push(
    `INSERT INTO questions (id, question_group_id, question_code, variant_code, prompt_text, option_a, option_b, option_c, option_d, correct_answer, explanation, created_at) ` +
      `VALUES (${groupId}, ${groupId}, '${code}', '01', ${q(item.prompt)}, ${q(a)}, ${q(b)}, ${q(c)}, ${q(d)}, '${item.correct}', NULL, ${SEED_TS});`,
  );
};

for (const item of LISTENING) emit(item, 'A', item.n);
for (const item of READING) emit(item, 'B', 20 + item.passage);
lines.push('');

// score_conversion_bands: per-part grids
CONVERSION_BANDS.partA.forEach((band, i) => {
  lines.push(
    `INSERT INTO score_conversion_bands (test_id, test_part_id, min_correct, max_correct, band_key, cefr_label, ielts_indicative, toefl_indicative, sort_order) ` +
      `VALUES (2, 3, ${band.min}, ${band.max}, ${q(band.key)}, ${q(band.label)}, ${q(band.ielts)}, ${q(band.toefl)}, ${i + 1});`,
  );
});
CONVERSION_BANDS.partB.forEach((band, i) => {
  lines.push(
    `INSERT INTO score_conversion_bands (test_id, test_part_id, min_correct, max_correct, band_key, cefr_label, ielts_indicative, toefl_indicative, sort_order) ` +
      `VALUES (2, 4, ${band.min}, ${band.max}, ${q(band.key)}, ${q(band.label)}, ${q(band.ielts)}, ${q(band.toefl)}, ${i + 1});`,
  );
});
lines.push('');

const outPath = join(ROOT, 'migrations', '0008_seed_test2.sql');
writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(`Wrote ${outPath} (${lines.length} lines, ${LISTENING.length + READING.length} groups+variants, ${LISTENING.length + PASSAGES.length} resources)`);
