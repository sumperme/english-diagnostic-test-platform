// Generates migrations/0015_seed_test3.sql from scripts/test3-content.mjs.
// Run: node scripts/generate-test3-seed.mjs
// ID allocation:
//   tests: 3 | test_parts: 5 (Speaking), 6 (Writing)
//   dimensions: 17-24 speaking skills, 25-26 writing skills
//   shared_resources: 27-33 audio (Tasks 1-7), 34 writing passage
//   question_groups & questions: 200 + n (201-210)

import { writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TEST3, SPEAKING, WRITING, WRITING_PASSAGE, CONVERSION_BANDS } from './test3-content.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SEED_TS = 1753027200000;

const q = (s) => (s == null ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`);
const pad2 = (n) => String(n).padStart(2, '0');
const pad3 = (n) => String(n).padStart(3, '0');

if (SPEAKING.length !== 8) throw new Error(`Expected 8 speaking tasks, got ${SPEAKING.length}`);
if (WRITING.length !== 2) throw new Error(`Expected 2 writing tasks, got ${WRITING.length}`);

const lines = [];
lines.push('-- Seed: Test 3 (Paper III — Speaking & Writing) into the unified test bank.');
lines.push('-- GENERATED by scripts/generate-test3-seed.mjs from scripts/test3-content.mjs — do not hand-edit.');
lines.push('-- 8 speaking groups (7 audio prompts + Task 8 prep) + 2 writing groups.');
lines.push('');

lines.push(
  `INSERT INTO tests (id, test_code, name, description, time_limit_seconds, status, created_at) VALUES (3, '03', ${q(TEST3.name)}, ${q(TEST3.description)}, ${TEST3.timeLimitSeconds}, 'draft', ${SEED_TS});`,
);
lines.push('');

lines.push(`INSERT INTO test_parts (id, test_id, part_code, name, skill, sort_order) VALUES (5, 3, '01', ${q('Part A — Speaking')}, 'speaking', 1);`);
lines.push(`INSERT INTO test_parts (id, test_id, part_code, name, skill, sort_order) VALUES (6, 3, '02', ${q('Part B — Writing')}, 'writing', 2);`);
lines.push('');

let dimId = 17;
for (const item of SPEAKING) {
  const ss = pad2(item.n);
  lines.push(
    `INSERT INTO dimensions (id, test_part_id, dimension_code, key, name, short, sort_order) VALUES (${dimId}, 5, ${q(ss)}, ${q(item.key)}, ${q(item.name)}, ${q(item.short)}, ${item.n});`,
  );
  dimId += 1;
}
for (const item of WRITING) {
  const local = item.n - 8;
  const ss = pad2(local);
  lines.push(
    `INSERT INTO dimensions (id, test_part_id, dimension_code, key, name, short, sort_order) VALUES (${dimId}, 6, ${q(ss)}, ${q(item.key)}, ${q(item.name)}, ${q(item.short)}, ${local});`,
  );
  dimId += 1;
}
lines.push('');

// Audio resources 27-33 for tasks 1-7
for (const item of SPEAKING.filter((s) => s.hasAudio)) {
  const resourceId = 26 + item.n;
  const file = `Speaking_Prompt_Task_${item.n}.mp3`;
  const meta = JSON.stringify({
    file,
    task: item.n,
    maxSeconds: item.maxSeconds,
    prepSeconds: item.prepSeconds,
    overlay: item.overlay ?? null,
    skill: item.skill,
  });
  lines.push(
    `INSERT INTO shared_resources (id, test_id, resource_type, title, content_url, text_content, metadata, created_at) ` +
      `VALUES (${resourceId}, 3, 'audio', ${q(`Speaking Prompt Task ${item.n}`)}, ${q(`/api/assets/audio/test-03/${file}`)}, NULL, ${q(meta)}, ${SEED_TS});`,
  );
}
lines.push('');

// Writing passage resource 34
lines.push(
  `INSERT INTO shared_resources (id, test_id, resource_type, title, content_url, text_content, metadata, created_at) ` +
    `VALUES (34, 3, 'text', ${q(WRITING_PASSAGE.title)}, NULL, ${q(WRITING_PASSAGE.text)}, ${q(JSON.stringify({ genre: 'argumentative source', task: 1 }))}, ${SEED_TS});`,
);
lines.push('');

// Speaking groups + questions
for (const item of SPEAKING) {
  const groupId = 200 + item.n;
  const ss = pad2(item.n);
  const ggg = pad3(item.n);
  const code = `03-01-${ss}-${ggg}-01`;
  const resourceId = item.hasAudio ? 26 + item.n : null;
  const dimIdFor = 16 + item.n;
  const meta = JSON.stringify({
    responseType: 'speaking',
    maxSeconds: item.maxSeconds,
    prepSeconds: item.prepSeconds,
    overlay: item.overlay ?? null,
    instructions: item.instructions,
  });
  lines.push(
    `INSERT INTO question_groups (id, test_id, test_part_id, dimension_id, shared_resource_id, group_code, canonical_number, legacy_qid, variant_count, sort_order, response_type) ` +
      `VALUES (${groupId}, 3, 5, ${dimIdFor}, ${resourceId == null ? 'NULL' : resourceId}, ${q(ggg)}, ${item.n}, ${q(`S${item.n}`)}, 1, ${item.n}, 'speaking');`,
  );
  // Store timing/overlay in explanation JSON; empty MCQ options for non-MCQ rows
  lines.push(
    `INSERT INTO questions (id, question_group_id, question_code, variant_code, prompt_text, option_a, option_b, option_c, option_d, correct_answer, explanation, created_at) ` +
      `VALUES (${groupId}, ${groupId}, ${q(code)}, '01', ${q(item.prompt)}, '', '', '', '', 'N/A', ${q(meta)}, ${SEED_TS});`,
  );
}
lines.push('');

// Writing groups + questions
for (const item of WRITING) {
  const groupId = 200 + item.n;
  const local = item.n - 8;
  const ss = pad2(local);
  const ggg = pad3(item.n);
  const code = `03-02-${ss}-${ggg}-01`;
  const resourceId = item.hasPassage ? 34 : null;
  const dimIdFor = 24 + local;
  const meta = JSON.stringify({
    responseType: 'writing',
    wordMin: item.wordMin,
    wordMax: item.wordMax,
    guidelines: item.guidelines,
  });
  lines.push(
    `INSERT INTO question_groups (id, test_id, test_part_id, dimension_id, shared_resource_id, group_code, canonical_number, legacy_qid, variant_count, sort_order, response_type) ` +
      `VALUES (${groupId}, 3, 6, ${dimIdFor}, ${resourceId == null ? 'NULL' : resourceId}, ${q(ggg)}, ${item.n}, ${q(`W${local}`)}, 1, ${item.n}, 'writing');`,
  );
  lines.push(
    `INSERT INTO questions (id, question_group_id, question_code, variant_code, prompt_text, option_a, option_b, option_c, option_d, correct_answer, explanation, created_at) ` +
      `VALUES (${groupId}, ${groupId}, ${q(code)}, '01', ${q(item.prompt)}, '', '', '', '', 'N/A', ${q(meta)}, ${SEED_TS});`,
  );
}
lines.push('');

// Conversion bands: qualitative level indices 0=B1/B2, 1=C1, 2=C2 (used after AI mark aggregation)
for (const [part, partId] of [
  ['speaking', 5],
  ['writing', 6],
]) {
  let sort = 1;
  for (const band of CONVERSION_BANDS[part]) {
    lines.push(
      `INSERT INTO score_conversion_bands (test_id, test_part_id, min_correct, max_correct, band_key, cefr_label, ielts_indicative, toefl_indicative, sort_order) ` +
        `VALUES (3, ${partId}, ${band.min}, ${band.max}, ${q(band.bandKey)}, ${q(band.cefr)}, ${q(band.ielts)}, ${q(band.toefl)}, ${sort});`,
    );
    sort += 1;
  }
}

const out = join(ROOT, 'migrations', '0015_seed_test3.sql');
writeFileSync(out, lines.join('\n') + '\n', 'utf8');
console.log(`Wrote ${out} (${lines.length} statements)`);
