// Generates migrations/0007_seed_test1.sql from the legacy frontend test bank
// (frontend/src/data/questions.ts, dimensions.ts, cefr.ts).
// Run: node scripts/generate-test1-seed.mjs
// See DATABASE_README.md section 9 for the mapping rules.

import { build } from 'esbuild';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SEED_TS = 1751860800000; // fixed timestamp for deterministic regeneration

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const pad2 = (n) => String(n).padStart(2, '0');
const pad3 = (n) => String(n).padStart(3, '0');

async function loadData() {
  const tmp = mkdtempSync(join(tmpdir(), 'edt-seed-'));
  const entry = join(tmp, 'entry.ts');
  writeFileSync(
    entry,
    `export { PART_A, PART_B, ALL_QUESTIONS, ANSWER_KEY } from '${pathToFileURL(join(ROOT, 'frontend/src/data/questions.ts')).href.slice(8)}';
export { DIMENSIONS, OVERALL_ONLY_QIDS } from '${pathToFileURL(join(ROOT, 'frontend/src/data/dimensions.ts')).href.slice(8)}';
export { CEFR_BANDS } from '${pathToFileURL(join(ROOT, 'frontend/src/data/cefr.ts')).href.slice(8)}';
`.replace(/\\/g, '/'),
  );
  const out = join(tmp, 'bundle.mjs');
  await build({ entryPoints: [entry], bundle: true, format: 'esm', outfile: out, platform: 'node' });
  const mod = await import(pathToFileURL(out).href);
  rmSync(tmp, { recursive: true, force: true });
  return mod;
}

const BAND_KEYS = { '≤A2': 'a2below', B1: 'b1', B2: 'b2', C1: 'c1', C2: 'c2' };

const { ALL_QUESTIONS, ANSWER_KEY, DIMENSIONS, CEFR_BANDS } = await loadData();

// --- Invariant checks (fail fast rather than emit a bad seed) ---
if (ALL_QUESTIONS.length !== 90) throw new Error(`Expected 90 questions, got ${ALL_QUESTIONS.length}`);
if (Object.keys(ANSWER_KEY).length !== 90) throw new Error('ANSWER_KEY size mismatch');
if (DIMENSIONS.length !== 12) throw new Error('Expected 12 dimensions');
const qidToDim = new Map();
for (const d of DIMENSIONS) {
  for (const qid of d.qids) {
    if (qidToDim.has(qid)) throw new Error(`qid ${qid} in multiple dimensions`);
    qidToDim.set(qid, d);
  }
}
for (const question of ALL_QUESTIONS) {
  if (!ANSWER_KEY[question.id]) throw new Error(`No answer for ${question.id}`);
  if (question.opts.length !== 4) throw new Error(`${question.id} does not have 4 options`);
  if (question.part === 'A' && !qidToDim.has(question.id)) throw new Error(`Part A qid ${question.id} missing dimension`);
}

const lines = [];
lines.push('-- Seed: Test 1 (Grammar & Vocabulary) into the unified test bank.');
lines.push('-- GENERATED by scripts/generate-test1-seed.mjs from frontend/src/data/*.ts — do not hand-edit.');
lines.push('-- 90 question groups (1 variant each), 12 Part A dimensions, overall CEFR grid 0-90.');
lines.push('');

// tests (id 1)
lines.push(
  `INSERT INTO tests (id, test_code, name, description, time_limit_seconds, status, created_at) VALUES (1, '01', ${q('Test 1 — Grammar & Vocabulary')}, ${q('CEFR-aligned English Diagnostic Test, Paper I: 60 applied grammar MCQs (12 dimensions) and 30 vocabulary MCQs.')}, 3600, 'active', ${SEED_TS});`,
);
lines.push('');

// test_parts (ids 1, 2)
lines.push(`INSERT INTO test_parts (id, test_id, part_code, name, skill, sort_order) VALUES (1, 1, '01', ${q('Part A — Applied Grammar')}, 'grammar', 1);`);
lines.push(`INSERT INTO test_parts (id, test_id, part_code, name, skill, sort_order) VALUES (2, 1, '02', ${q('Part B — Vocabulary')}, 'vocabulary', 2);`);
lines.push('');

// dimensions (ids 1..12 on part 1); dimension_code = zero-padded legacy id
for (const d of DIMENSIONS) {
  lines.push(
    `INSERT INTO dimensions (id, test_part_id, dimension_code, key, name, short, sort_order) VALUES (${d.id}, 1, '${pad2(d.id)}', ${q(d.key)}, ${q(d.name)}, ${q(d.short)}, ${d.id});`,
  );
}
lines.push('');

// question_groups (id = canonicalNumber, 1..90) + questions (same ids)
for (const question of ALL_QUESTIONS) {
  const canonical = question.canonicalNumber;
  const partId = question.part === 'A' ? 1 : 2;
  const partCode = question.part === 'A' ? '01' : '02';
  const dim = question.part === 'A' ? qidToDim.get(question.id) : null;
  const dimId = dim ? dim.id : 'NULL';
  const ss = dim ? pad2(dim.id) : '00';
  const ggg = pad3(canonical);
  const code = `01-${partCode}-${ss}-${ggg}-01`;

  lines.push(
    `INSERT INTO question_groups (id, test_id, test_part_id, dimension_id, shared_resource_id, group_code, canonical_number, legacy_qid, variant_count, sort_order) ` +
      `VALUES (${canonical}, 1, ${partId}, ${dimId}, NULL, '${ggg}', ${canonical}, ${q(question.id)}, 1, ${canonical});`,
  );
  const [a, b, c, d] = question.opts.map((o) => o.t);
  lines.push(
    `INSERT INTO questions (id, question_group_id, question_code, variant_code, prompt_text, option_a, option_b, option_c, option_d, correct_answer, explanation, created_at) ` +
      `VALUES (${canonical}, ${canonical}, '${code}', '01', ${q(question.text)}, ${q(a)}, ${q(b)}, ${q(c)}, ${q(d)}, '${ANSWER_KEY[question.id]}', NULL, ${SEED_TS});`,
  );
}
lines.push('');

// score_conversion_bands: overall grid (test_part_id NULL)
CEFR_BANDS.forEach((band, i) => {
  const key = BAND_KEYS[band.cefr];
  if (!key) throw new Error(`No band key mapping for ${band.cefr}`);
  lines.push(
    `INSERT INTO score_conversion_bands (test_id, test_part_id, min_correct, max_correct, band_key, cefr_label, ielts_indicative, toefl_indicative, sort_order) ` +
      `VALUES (1, NULL, ${band.min}, ${band.max}, ${q(key)}, ${q(band.cefr)}, ${q(band.ielts)}, ${q(band.toefl)}, ${i + 1});`,
  );
});
lines.push('');

const outPath = join(ROOT, 'migrations', '0007_seed_test1.sql');
writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(`Wrote ${outPath} (${lines.length} lines, ${ALL_QUESTIONS.length} groups+variants)`);
